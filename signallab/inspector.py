"""Inspect real numeric MATLAB variables without inventing class labels."""

import tkinter as tk
from pathlib import Path
from tkinter import filedialog, messagebox, ttk

import numpy as np
from matplotlib.backends.backend_tkagg import FigureCanvasTkAgg, NavigationToolbar2Tk
from matplotlib.figure import Figure

from . import core


class MATInspector:
    def __init__(self, root):
        self.root = root
        root.title("SignalLab | MATLAB Inspector")
        root.geometry("1280x850")
        root.minsize(1000, 700)
        self.data = {}
        self.signals = None
        self.key = ""
        self.path = None
        self.fs = tk.DoubleVar(value=1024)
        self.columns = tk.BooleanVar(value=False)
        self.index = tk.IntVar(value=0)
        style = ttk.Style(root)
        style.theme_use("clam")
        style.configure(
            ".", font=("Segoe UI", 10), background="#f1f5f9", foreground="#172b4d"
        )
        style.configure("TButton", padding=(10, 6))
        style.configure(
            "Treeview", rowheight=27, background="white", fieldbackground="white"
        )
        header = ttk.Frame(root, padding=(18, 12))
        header.pack(fill="x")
        ttk.Label(
            header, text="SignalLab / MATLAB Inspector", font=("Segoe UI", 19, "bold")
        ).pack(side="left")
        ttk.Button(header, text="Open MATLAB dataset", command=self.load).pack(
            side="right"
        )
        self.status = ttk.Label(
            root,
            text="Open a .mat file to inspect variables. Sampling rate is user supplied.",
            padding=(18, 6),
        )
        self.status.pack(fill="x")
        split = ttk.Panedwindow(root, orient="horizontal")
        split.pack(fill="both", expand=True, padx=14, pady=10)
        left = ttk.Frame(split, padding=8)
        right = ttk.Frame(split, padding=8)
        split.add(left, weight=1)
        split.add(right, weight=3)
        ttk.Label(left, text="Dataset variables", font=("Segoe UI", 12, "bold")).pack(
            anchor="w", pady=(0, 8)
        )
        table = ttk.Frame(left)
        table.pack(fill="both", expand=True)
        self.tree = ttk.Treeview(
            table,
            columns=("variable", "shape", "type"),
            show="headings",
            height=10,
            selectmode="browse",
        )
        for name, width in [("variable", 125), ("shape", 125), ("type", 85)]:
            self.tree.heading(name, text=name.title())
            self.tree.column(name, width=width, minwidth=65)
        scroll = ttk.Scrollbar(table, orient="vertical", command=self.tree.yview)
        self.tree.configure(yscrollcommand=scroll.set)
        self.tree.grid(row=0, column=0, sticky="nsew")
        scroll.grid(row=0, column=1, sticky="ns")
        table.rowconfigure(0, weight=1)
        table.columnconfigure(0, weight=1)
        ttk.Checkbutton(
            left,
            text="Signals are columns (transpose)",
            variable=self.columns,
            command=self.select,
        ).pack(anchor="w", pady=(12, 6))
        ttk.Label(left, text="Sampling rate (Hz) - enter the actual value").pack(
            anchor="w"
        )
        entry = ttk.Entry(left, textvariable=self.fs, width=14)
        entry.pack(anchor="w", pady=5)
        entry.bind("<Return>", lambda event: self.render())
        ttk.Button(left, text="Apply sampling rate", command=self.render).pack(
            anchor="w"
        )
        ttk.Label(left, text="Signal index (zero based)").pack(anchor="w", pady=(12, 3))
        self.slider = ttk.Scale(left, from_=0, to=0, command=self.move)
        self.slider.pack(fill="x")
        row = ttk.Frame(left)
        row.pack(fill="x", pady=5)
        self.spin = ttk.Spinbox(
            row, from_=0, to=0, textvariable=self.index, width=9, command=self.render
        )
        self.spin.pack(side="left")
        self.spin.bind("<Return>", lambda event: self.render())
        self.count = ttk.Label(row, text="No signal selected")
        self.count.pack(side="left", padx=8)
        self.stats = tk.Text(
            left,
            height=12,
            width=38,
            wrap="word",
            font=("Consolas", 10),
            relief="flat",
            padx=8,
            pady=8,
        )
        self.stats.pack(fill="x", pady=10)
        self.stats.configure(state="disabled")
        self.report_button = ttk.Button(
            left, text="Open detailed report", command=self.report, state="disabled"
        )
        self.report_button.pack(fill="x", pady=5)
        ttk.Label(
            left,
            text="Real numeric vectors/matrices only.\nMATLAB v7.3: resave as -v7.\nNo labels are generated by this inspector.",
            wraplength=320,
        ).pack(anchor="w", pady=8)
        self.figure = Figure(figsize=(8, 6))
        self.axes = self.figure.subplots(2, 1)
        self.figure.tight_layout(pad=3)
        self.canvas = FigureCanvasTkAgg(self.figure, master=right)
        toolbar = NavigationToolbar2Tk(self.canvas, right, pack_toolbar=False)
        toolbar.pack(side="bottom", fill="x")
        self.canvas.get_tk_widget().pack(fill="both", expand=True)
        self.tree.bind("<<TreeviewSelect>>", self.select)
        for ax, title in zip(
            self.axes, ["Select a numeric variable", "Power spectrum"]
        ):
            ax.set_title(title)
            ax.grid(alpha=0.2)
        self.canvas.draw()

    def load(self):
        path = filedialog.askopenfilename(filetypes=[("MATLAB datasets", "*.mat")])
        if not path:
            return
        try:
            data = core.read_mat(path)
        except Exception as error:
            messagebox.showerror("MATLAB load", str(error))
            return
        self.data = data
        self.path = Path(path)
        self.signals = None
        self.key = ""
        self.tree.delete(*self.tree.get_children())
        self.report_button.configure(state="disabled")
        self.stats.configure(state="normal")
        self.stats.delete("1.0", "end")
        self.stats.configure(state="disabled")
        for ax in self.axes:
            ax.clear()
        self.canvas.draw()
        for key, value in data.items():
            array = np.asarray(value)
            self.tree.insert(
                "", "end", iid=key, values=(key, str(array.shape), str(array.dtype))
            )
        self.status.configure(
            text=f"{self.path.name} | {len(data)} variables | select a real numeric array"
        )

    def select(self, event=None):
        selected = self.tree.selection()
        if not selected:
            return
        key = selected[0]
        try:
            matrix = core.signal_matrix(
                self.data[key], sample_axis=0 if self.columns.get() else 1
            )
        except Exception as error:
            self.signals = None
            self.report_button.configure(state="disabled")
            self.status.configure(text=f"{key}: {error}")
            return
        self.key = key
        self.signals = matrix
        self.index.set(0)
        self.slider.configure(to=max(0, len(matrix) - 1))
        self.slider.set(0)
        self.spin.configure(to=len(matrix) - 1)
        self.report_button.configure(state="normal")
        self.render()

    def move(self, value):
        if self.signals is None:
            return
        self.index.set(min(len(self.signals) - 1, max(0, int(float(value)))))
        self.render()

    def selected(self):
        if self.signals is None:
            raise ValueError("Select a real numeric signal variable first.")
        idx = int(self.index.get())
        fs = float(self.fs.get())
        if not 0 <= idx < len(self.signals):
            raise ValueError("Signal index is out of range.")
        if not np.isfinite(fs) or fs <= 0:
            raise ValueError("Sampling rate must be finite and positive.")
        return self.signals[idx], fs, idx

    def render(self):
        if self.signals is None:
            return
        try:
            signal, fs, idx = self.selected()
        except Exception as error:
            self.status.configure(text=str(error))
            return
        f, p = core.spectrum(signal, fs)
        a, b = self.axes
        a.clear()
        b.clear()
        a.plot(np.arange(len(signal)) / fs, signal, color="#087f8c", linewidth=0.8)
        a.set(title=f"{self.key} / signal {idx}", xlabel="Time (s)", ylabel="Amplitude")
        b.plot(f, p, color="#d97706", linewidth=0.9)
        b.set(
            title="One-sided mean-square contributions",
            xlabel="Frequency (Hz)",
            ylabel="Power per FFT bin",
        )
        for ax in self.axes:
            ax.grid(alpha=0.2)
        self.figure.tight_layout(pad=2)
        self.canvas.draw_idle()
        values = core.time_features(signal)
        values.update(
            energy=float(signal @ signal),
            samples=len(signal),
            total_power=float(p.sum()),
        )
        self.stats.configure(state="normal")
        self.stats.delete("1.0", "end")
        self.stats.insert(
            "end", "\n".join(f"{key:16} {value:.6g}" for key, value in values.items())
        )
        self.stats.configure(state="disabled")
        self.count.configure(text=f"of {len(self.signals)} signals")
        self.status.configure(
            text=f"{self.path.name if self.path else 'MAT'} | {self.key} | {self.signals.shape} | {fs:g} Hz"
        )

    def report(self):
        try:
            signal, fs, idx = self.selected()
        except Exception as error:
            messagebox.showerror("Report", str(error))
            return
        win = tk.Toplevel(self.root)
        win.title(f"SignalLab report | {self.key} / {idx}")
        win.geometry("1100x800")
        fig = Figure(figsize=(10, 7))
        axes = fig.subplots(2, 2)
        f, p = core.spectrum(signal, fs)
        axes[0, 0].plot(np.arange(len(signal)) / fs, signal, linewidth=0.8)
        axes[0, 0].set(title="Waveform", xlabel="Time (s)", ylabel="Amplitude")
        axes[0, 1].plot(f, p)
        axes[0, 1].set(
            title="Power spectrum", xlabel="Frequency (Hz)", ylabel="Power per FFT bin"
        )
        axes[1, 0].hist(signal, bins=min(50, max(4, int(np.sqrt(len(signal))))))
        axes[1, 0].set(title="Value distribution", xlabel="Amplitude", ylabel="Count")
        nfft = min(256, 2 ** int(np.floor(np.log2(len(signal)))))
        axes[1, 1].specgram(signal, NFFT=nfft, Fs=fs, noverlap=nfft // 2)
        axes[1, 1].set(
            title="Spectrogram (power density, dB)",
            xlabel="Time (s)",
            ylabel="Frequency (Hz)",
        )
        fig.suptitle(f"{self.key} / signal {idx} | {fs:g} Hz")
        fig.tight_layout()
        canvas = FigureCanvasTkAgg(fig, master=win)
        toolbar = NavigationToolbar2Tk(canvas, win, pack_toolbar=False)
        toolbar.pack(side="bottom", fill="x")
        canvas.get_tk_widget().pack(fill="both", expand=True)
        canvas.draw()


def main():
    root = tk.Tk()
    MATInspector(root)
    root.mainloop()


if __name__ == "__main__":
    main()
